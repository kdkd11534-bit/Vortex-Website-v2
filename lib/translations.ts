export function getTranslations(locale: Locale): TranslationKeys {
  return translations[locale] || translations.en
}

export function detectLocale(): Locale {
  if (typeof window === "undefined") return "en"

  // Get browser language
  const browserLang = navigator.language || (navigator as unknown as { userLanguage?: string }).userLanguage || "en"

  // Extract the base language code (e.g., "fr" from "fr-FR")
  const baseLang = browserLang.split("-")[0].toLowerCase()

  // Check if it's a supported locale
  if (SUPPORTED_LOCALES.includes(baseLang as Locale)) {
    return baseLang as Locale
  }

  return "en"
}
